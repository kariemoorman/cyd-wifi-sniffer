    features = load_features(args.data_dir)

    print("Loading labels...")
    labels = load_labels(args.data_dir)

    if args.model in ("lstm_lr", "gru_lr", "rnn_lr"):
        train_hybrid(features, labels, args)
    else:
        X_train, y_train, X_test, y_test, scaler = prepare_flat_data(features, labels)
        print(f"Model: {args.model}")
