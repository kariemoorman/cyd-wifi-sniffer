def assemble_windows(data_dir: str, window_size: int):
    """Build sliding time-series windows from all feature rows.

    Every row in every feat_N.csv is treated as one timestep.  Files are
    processed in sorted order so rows from feat_2 come before feat_4, etc.
    For each src_mac we concatenate all its rows chronologically, then
    extract stride-1 sliding windows of ``window_size`` consecutive steps.
    Short sequences are zero-padded on the left.

    Returns
    -------
    windows : dict[str, np.ndarray]
        mac -> (n_windows, window_size, n_features)
    file_order : list[str]
        Ordered list of feature files used.
    """
    pattern = os.path.join(data_dir, "feat_*.csv")
    files = sorted(glob.glob(pattern))
    if not files:
        raise FileNotFoundError(f"No feature files matching {pattern}")

    print(f"  Found {len(files)} feature files for windowing")

    # Collect ALL rows per MAC across files in chronological order
    mac_series: dict = {}
    total_rows = 0
    for fpath in files:
        df = pd.read_csv(fpath)
        for mac, group in df.groupby("src_mac"):
            rows = group[FEATURE_COLS].values.astype(np.float32)
            if mac not in mac_series:
                mac_series[mac] = []
            mac_series[mac].append(rows)
            total_rows += len(rows)

    print(f"  Total rows across all MACs: {total_rows}")

    n_features = len(FEATURE_COLS)
    windows: dict = {}

    for mac, row_blocks in mac_series.items():
        # Concatenate all rows for this MAC in file order
        seq = np.concatenate(row_blocks, axis=0)  # (T, n_features)
        T = len(seq)

        if T < window_size:
            pad = np.zeros((window_size - T, n_features), dtype=np.float32)
            seq = np.concatenate([pad, seq], axis=0)
            T = window_size

        n_win = T - window_size + 1
        wins = np.array([seq[i:i + window_size] for i in range(n_win)],
                        dtype=np.float32)
        windows[mac] = wins

    total_wins = sum(w.shape[0] for w in windows.values())
    print(f"  Assembled {total_wins} windows across {len(windows)} MACs "
          f"(window_size={window_size}, stride=1)")
    return windows, files

def _build_output_heads(shared):
    """Attach 5 Dense+softmax (logistic-regression) output heads."""
    anomaly_out = tf.keras.layers.Dense(
        len(ANOMALY_CLASSES), activation="softmax", name="anomaly"
    )(shared)
    packet_out = tf.keras.layers.Dense(
        len(PACKET_CLASSES), activation="softmax", name="packet_class"
    )(shared)
    protocol_out = tf.keras.layers.Dense(
        len(PROTOCOL_CLASSES), activation="softmax", name="protocol"
    )(shared)
    device_out = tf.keras.layers.Dense(
        len(DEVICE_CLASSES), activation="softmax", name="device_type"
    )(shared)
    route_out = tf.keras.layers.Dense(
        len(ROUTE_ACTIONS), activation="softmax", name="route_action"
    )(shared)
    return [anomaly_out, packet_out, protocol_out, device_out, route_out]


def _compile_model(model):
    """Shared compile configuration for hybrid models."""
    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=1e-3),
        loss={
            "anomaly": "sparse_categorical_crossentropy",
            "packet_class": "sparse_categorical_crossentropy",
            "protocol": "sparse_categorical_crossentropy",
            "device_type": "sparse_categorical_crossentropy",
            "route_action": "sparse_categorical_crossentropy",
        },
        metrics={
            "anomaly": ["accuracy"],
            "packet_class": ["accuracy"],
            "protocol": ["accuracy"],
            "device_type": ["accuracy"],
            "route_action": ["accuracy"],
        },
    )
    return model


def build_hybrid_lr(arch: str, window_size: int, n_features: int):
    """Build RNN temporal encoder -> Dense+softmax (LR) heads."""
    layer_cls = RNN_LAYERS[arch]
    inputs = tf.keras.Input(shape=(window_size, n_features), name="sequence")
    x = layer_cls(64, return_sequences=False, unroll=True)(inputs)
    x = tf.keras.layers.BatchNormalization()(x)
    shared = tf.keras.layers.Dropout(0.3)(x)
    outputs = _build_output_heads(shared)
    model = tf.keras.Model(inputs=inputs, outputs=outputs)
    return _compile_model(model)


def train_hybrid(features, labels, args):
    """Train a hybrid RNN+LR model using time-series windows.
    Hybrid models (LSTM_LR, GRU_LR, RNN_LR)combine deep sequence models with 
    classical classifiers: Temporal feature extraction via 
    RNN backbone + Dense+softmax (logistic regression) output heads.
    """

    model_name = args.model.upper().replace("_", " -> ")
    print(f"\n{'='*60}")
    print(f"Hybrid model: {model_name}")
    print(f"Window size:  {args.window_size}")
    print(f"{'='*60}")

    # 1) Assemble windows
    print("\nAssembling time-series windows...")
    windows, _ = assemble_windows(args.data_dir, args.window_size)

    # 2) Encode labels (one label per MAC — broadcast to all windows)
    labels_df = labels.copy()
    labels_df, encoders = encode_labels(labels_df)

    enc_cols = [n + "_enc" for n in OUTPUT_NAMES]

    X_list = []
    y_lists = [[] for _ in OUTPUT_NAMES]

    for _, row in labels_df.iterrows():
        mac = row["src_mac"]
        if mac not in windows:
            continue
        wins = windows[mac]
        X_list.append(wins)
        for j, col in enumerate(enc_cols):
            y_lists[j].extend([row[col]] * len(wins))

    if not X_list:
        raise ValueError(
            "No labeled MACs found in windowed data. "
            "Check that labels.csv MACs match feat_*.csv MACs."
        )

    X_all = np.concatenate(X_list, axis=0)
    y_all = [np.array(y, dtype=np.int32) for y in y_lists]

    print(f"  Total windows: {len(X_all)}")
    print(f"  Shape: {X_all.shape}")

    # 3) Scale features (per-timestep, same scaler logic as flat model)
    scaler = StandardScaler()
    orig_shape = X_all.shape
    X_flat = X_all.reshape(-1, X_all.shape[-1])
    X_flat = scaler.fit_transform(X_flat)
    X_all = X_flat.reshape(orig_shape).astype(np.float32)

    # 4) Train/test split
    # mac_labels = labels_df.set_index("src_mac")["anomaly"]
    # # unique_macs = labels_df["src_mac"].unique()
    # unique_macs = mac_labels.index.values
    # strat_key = mac_labels.values
    # train_macs, test_macs = train_test_split(unique_macs, test_size=0.2, random_state=42, stratify=strat_key)
    # train_mask = labels_df["src_mac"].isin(train_macs)
    # train_idx = np.where(train_mask)[0]
    # test_idx = np.where(~train_mask)[0]
    indices = np.arange(len(X_all))
    train_idx, test_idx = train_test_split(indices, test_size=0.2, random_state=42, stratify=y_all[1])

    X_train, X_test = X_all[train_idx], X_all[test_idx]
    y_train = [y[train_idx] for y in y_all]
    y_test = [y[test_idx] for y in y_all]

    print(f"  Train: {len(X_train)}, Test: {len(X_test)}")

    # 5) Class balancing
    sample_weights = prepare_balance_weights(y_train, args)

    # 6) Build model
    n_features = X_all.shape[-1]
    model = build_hybrid_lr(args.model, args.window_size, n_features)
    model.summary()
    print()

    # 7) Train
    fit_model(model, X_train, y_train, X_test, y_test, sample_weights, args)

    # 8) Evaluate Model Performance
    evaluate_model(model, X_test, y_test, model_name)

    # 9) Export Model
    convert_to_tflite(model, scaler, X_train, args)


